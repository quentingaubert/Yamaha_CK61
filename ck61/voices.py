def voice_number(name):
    """Retourne la Parameter Value d'une voix (recherche insensible à la casse)."""
    lowered = name.lower()
    for i, voice in enumerate(VOICES):
        if voice.lower() == lowered:
            return i
    raise KeyError(f"Voix inconnue : {name!r}")


def category_of(number):
    """Retourne le numéro de catégorie (0-9) d'une voix."""
    for index in reversed(range(len(CATEGORIES))):
        if number >= CATEGORIES[index][1]:
            return index
    raise ValueError(number)
